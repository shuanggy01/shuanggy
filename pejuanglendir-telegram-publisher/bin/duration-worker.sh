#!/usr/bin/env bash
set -u

# shellcheck source=common.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

# Performance-safe mode: duration probing should yield to web traffic.
renice 10 -p $$ >/dev/null 2>&1 || true
ionice -c2 -n7 -p $$ >/dev/null 2>&1 || true


LOCK_FILE="/tmp/pejuanglendir-duration-worker.lock"

exec 9>"$LOCK_FILE"

if command -v flock >/dev/null 2>&1; then
    flock -n 9 || exit 0
fi

log() {
    printf '%s\n' "$*"
}

if [ ! -x "$PHP" ] || [ ! -f "$WP" ] || [ ! -x "$FFPROBE" ]; then
    log "ERROR: PHP/WP-CLI/FFprobe tidak tersedia"
    exit 1
fi

IDS="$(
    "$PHP" "$WP" post list \
        --post_type=post \
        --post_status=publish,draft \
        --meta_key=_pltp_duration_pending \
        --meta_value=1 \
        --orderby=ID \
        --order=ASC \
        --format=ids \
        --path="$ROOT" \
        2>/dev/null
)"

[ -n "$IDS" ] || exit 0

COUNT=0

for ID in $IDS; do
    COUNT=$((COUNT + 1))
    [ "$COUNT" -le 2 ] || break

    VIDEO_URL="$(
        "$PHP" "$WP" post meta get "$ID" video_url \
            --path="$ROOT" \
            2>/dev/null
    )"

    if [ -z "$VIDEO_URL" ]; then
        "$PHP" "$WP" post meta update "$ID" _pltp_duration_error \
            "video_url kosong" --path="$ROOT" >/dev/null 2>&1
        "$PHP" "$WP" post meta delete "$ID" _pltp_duration_pending \
            --path="$ROOT" >/dev/null 2>&1
        log "POST $ID ERROR video_url kosong"
        continue
    fi

    ATTEMPTS="$(
        "$PHP" "$WP" post meta get "$ID" _pltp_duration_attempts \
            --path="$ROOT" 2>/dev/null
    )"

    case "$ATTEMPTS" in
        ''|*[!0-9]*) ATTEMPTS=0 ;;
    esac

    RAW="$(
        timeout 25s "$FFPROBE" \
            -v error \
            -show_entries format=duration \
            -of default=noprint_wrappers=1:nokey=1 \
            "$VIDEO_URL" \
            2>/dev/null \
        | tail -n 1
    )"

    if ! awk -v d="$RAW" 'BEGIN { exit !(d+0 > 0.05) }'; then
        ATTEMPTS=$((ATTEMPTS + 1))

        "$PHP" "$WP" post meta update "$ID" _pltp_duration_attempts "$ATTEMPTS" \
            --path="$ROOT" >/dev/null 2>&1

        "$PHP" "$WP" post meta update "$ID" _pltp_duration_error \
            "FFprobe gagal membaca durasi (attempt $ATTEMPTS/3)" \
            --path="$ROOT" >/dev/null 2>&1

        if [ "$ATTEMPTS" -ge 3 ]; then
            "$PHP" "$WP" post meta delete "$ID" _pltp_duration_pending \
                --path="$ROOT" >/dev/null 2>&1
        fi

        log "POST $ID ERROR ffprobe attempt=$ATTEMPTS"
        continue
    fi

    SECONDS="$(
        awk -v d="$RAW" 'BEGIN {
            s = int(d + 0.5);
            if (s < 1) s = 1;
            print s
        }'
    )"

    if ! PLTP_POST_ID="$ID" PLTP_SECONDS="$SECONDS" \
        "$PHP" "$WP" eval '
            $id = (int) getenv("PLTP_POST_ID");
            $seconds = (int) getenv("PLTP_SECONDS");

            update_post_meta($id, "duration", $seconds);
            update_post_meta($id, "_pltp_duration_seconds", $seconds);

            /*
             * Keep the persistent Rank Math VideoObject schema synchronized.
             * V1.7.3 also repairs older posts where this meta did not exist.
             */
            $video_url = (string) get_post_meta($id, "video_url", true);
            $schema = get_post_meta($id, "rank_math_schema_VideoObject", true);

            if (!is_array($schema) || empty($schema)) {
                $schema = [
                    "@type" => "VideoObject",
                    "metadata" => [
                        "title" => "Video",
                        "type" => "template",
                        "shortcode" => "s-" . substr(md5("pltp-video-" . $id), 0, 12),
                        "isPrimary" => true,
                        "reviewLocationShortcode" => "[rank_math_rich_snippet]",
                        "category" => "%categories%",
                        "tags" => "%tags%",
                        "isAutoGenerated" => true,
                        "duration" => $seconds,
                    ],
                    "name" => "%seo_title%",
                    "description" => "%seo_description%",
                    "uploadDate" => "%date(Y-m-dTH:i:sP)%",
                    "thumbnailUrl" => "%post_thumbnail%",
                    "embedUrl" => "",
                    "contentUrl" => esc_url_raw($video_url),
                    "duration" => "",
                    "width" => "",
                    "height" => "",
                    "isFamilyFriendly" => false,
                ];
            } else {
                $schema["@type"] = "VideoObject";
                $schema["contentUrl"] = esc_url_raw($video_url);

                if (!isset($schema["metadata"]) || !is_array($schema["metadata"])) {
                    $schema["metadata"] = [];
                }

                $schema["metadata"]["duration"] = $seconds;
            }

            update_post_meta(
                $id,
                "rank_math_schema_VideoObject",
                $schema
            );

            delete_post_meta($id, "_pltp_duration_pending");
            delete_post_meta($id, "_pltp_duration_attempts");
            delete_post_meta($id, "_pltp_duration_error");

            if (
                class_exists("PLTP_Publisher")
                && method_exists(
                    "PLTP_Publisher",
                    "refresh_smart_content"
                )
            ) {
                PLTP_Publisher::refresh_smart_content($id);
            }

            clean_post_cache($id);

        ' \
        --path="$ROOT" \
        >/dev/null 2>&1
    then
        log "POST $ID ERROR WordPress update"
        continue
    fi

    # Safe Rank Math video sitemap cache refresh.
    # Do not call RankMath\Sitemap\Cache::invalidate_storage() here:
    # WP-CLI on this aaPanel server can resolve WP_Filesystem to FTPext
    # without an FTP connection.
    "$PHP" "$WP" eval '
        global $wpdb;

        $like_transient = $wpdb->esc_like(
            "_transient_sitemap_video_"
        ) . "%";

        $like_timeout = $wpdb->esc_like(
            "_transient_timeout_sitemap_video_"
        ) . "%";

        $wpdb->query(
            $wpdb->prepare(
                "DELETE FROM {$wpdb->options}
                 WHERE option_name LIKE %s
                    OR option_name LIKE %s",
                $like_transient,
                $like_timeout
            )
        );

        if (class_exists("\\RankMath\\Helper")) {
            $files = \RankMath\Helper::option(
                "sitemap_cache_files"
            );

            if (is_array($files) && !empty($files)) {
                $uploads = wp_upload_dir();
                $dir = trailingslashit(
                    $uploads["basedir"]
                ) . "rank-math/";

                $keep = [];

                foreach ($files as $file => $type) {
                    if ("video" === (string) $type) {
                        $path = $dir . basename(
                            (string) $file
                        );

                        if (is_file($path)) {
                            @unlink($path);
                        }

                        continue;
                    }

                    $keep[$file] = $type;
                }

                \RankMath\Helper::option(
                    "sitemap_cache_files",
                    $keep
                );
            }
        }
    ' \
    --path="$ROOT" \
    >/dev/null 2>&1 || true

    H=$((SECONDS / 3600))
    M=$(((SECONDS % 3600) / 60))
    S=$((SECONDS % 60))

    printf -v CLOCK '%02d:%02d:%02d' "$H" "$M" "$S"

    log "POST $ID OK duration=${SECONDS}s clock=$CLOCK"
done
